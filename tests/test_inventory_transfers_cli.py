"""Task I UX lane (t_7ed909c9): read-only `inventory transfers` CLI wiring.

Covers the thin-wrapper contract: sdk/commands.py only dispatches,
reads the snapshots directory and the wall clock; every ounce of
transfer logic lives in the pure sdk/inventory/transfer.py module
(plan_transfers + render_transfers_view, covered by the planner,
adversarial and safety lanes). These tests exercise the REAL registry
handler path end to end against temp snapshot dirs.

Pins proven here:
- dispatch: `inventory transfers` reaches render_transfers_view via
  _render_portfolio_view; accounts/deficits unchanged.
- thin wrapper: commands.py never imports plan_transfers or the
  transfer module symbols; the only transfer import is the renderer;
  no new registered verb contains "transfer" (subcommand dispatch
  under the existing `inventory` verb only).
- read-only pairing view over persisted snapshots: source/destination
  accounts, ItemDesignId, proposed quantity 0, matched informational
  arithmetic, weakest-input evidence, per-side freshness, hold state,
  sorted reasons, actionable=false on every row.
- fail-closed whole-view refusal on malformed/duplicate/secret-bearing
  snapshots (same channel as accounts/deficits).
- empty/missing snapshot directory is an empty state, never an error.
- no network: the handler completes with sockets blocked.
- unknown subcommand help lists `inventory transfers`.

All snapshots are synthetic (schema-v1 loader shape). The Client is a
MagicMock; disk reads hit temp dirs only. NO live Pixel Starships
traffic is generated by this file.
"""

