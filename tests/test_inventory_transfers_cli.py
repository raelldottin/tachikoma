class TestThinWrapperContract(unittest.TestCase):
    """commands.py stays I/O + dispatch only for the transfers view."""

    def _registry(self):
        from sdk.commands import create_command_registry

        return create_command_registry(MagicMock())

    def test_no_new_registered_verb_contains_transfer(self):
        registry = self._registry()
        for name in registry.list_commands():
            self.assertNotIn("transfer", name)

    def test_commands_imports_renderer_but_never_planner(self):
        """The ONLY transfer import allowed in commands.py is the pure
        renderer; the planner and every transfer symbol stay in
        sdk/inventory (thin-wrapper contract, mirrors the safety lane's
        AST pin)."""
        import sdk.commands as commands_mod

        tree = ast.parse(inspect.getsource(commands_mod))
        transfer_imports = []
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module == "sdk.inventory":
                for alias in node.names:
                    if alias.name.startswith("transfer"):
                        transfer_imports.append(alias.name)
        self.assertEqual(transfer_imports, [])
        renderer_imports = [
            alias.name
            for node in ast.walk(tree)
            if isinstance(node, ast.ImportFrom)
            and node.module == "sdk.inventory"
            for alias in node.names
            if alias.name == "render_transfers_view"
        ]
        self.assertEqual(len(renderer_imports), 1)

    def test_transfers_handler_runs_with_sockets_blocked(self):
        def _blocked(*args, **kwargs):
            raise AssertionError("network I/O attempted during transfers view")

        registry = self._registry()
        with patch.object(socket, "socket", _blocked), patch.object(
            socket, "create_connection", _blocked
        ):
            out = registry.get("inventory")["handler"](["transfers"])
        # Empty state (MagicMock client, no snapshots dir contents) —
        # but reached WITHOUT any network attempt.
        self.assertIn("No account snapshots found", out)

    def test_transfers_reads_no_env_or_config_flags(self):
        path = os.path.join(os.path.dirname(__file__), "..",
                            "sdk", "commands.py")
        with open(path, encoding="utf-8") as f:
            src = f.read()
        self.assertNotIn("os.environ", src)
        self.assertNotIn("getenv", src)

    def test_commands_source_has_no_mutation_urls(self):
        path = os.path.join(os.path.dirname(__file__), "..",
                            "sdk", "commands.py")
        with open(path, encoding="utf-8") as f:
            src = f.read()
        for frag in (
            "/ItemService/GiftItem",
            "/MarketService/SellItem3",
            "/MarketService/Purchase4",
            "/ItemService/ConsumeItem2",
            "/ItemService/DeleteItem3",
        ):
            self.assertNotIn(frag, src)

    def test_apply_refusal_untouched_by_transfers_wiring(self):
        registry = self._registry()
        out = registry.get("inventory apply")["handler"]([])
        self.assertIn("REFUSED", out)


