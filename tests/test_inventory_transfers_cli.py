def snap_payload(user_id=101, display_name="alpha",
                 captured="2026-09-29T00:00:00Z", **overrides):
    payload = {
        "version": 1,
        "identity": {"user_id": user_id, "ship_id": 55,
                     "display_name": display_name},
        "stacks": [stack_row()],
        "designs": [design_row()],
        "conditions": [],
        "limitations": [],
        "captured_at": captured,
        "actionable": False,
    }
    payload.update(overrides)
    return payload


def source_payload(user_id=101, captured="2026-09-29T00:00:00Z"):
    """Account holding 10 free candidates of design 501 (no deficit)."""
    payload = snap_payload(user_id=user_id, display_name="donor",
                           captured=captured)
    payload["stacks"] = [stack_row(
        candidate_quantity=10, candidate_state="CANDIDATE",
        candidate_reasons=[], candidate_evidence="INFERRED",
        disposition_hint="USE",
    )]
    return payload


def deficit_payload(user_id=202, captured="2026-09-29T00:00:00Z"):
    """Account requesting 13 of design 501 against 10 observed (unmet 3).

    Producer-possible shape: the stack reserves 10 of the 13 requested
    against 10 observed, so its own candidate is 0/HOLD (nothing
    unreserved), while the design row records unmet 3.
    """
    payload = snap_payload(user_id=user_id, display_name="recipient",
                           captured=captured)
    payload["stacks"] = [stack_row(
        item_id=2001, requested_quantity=13, reserved_quantity=10,
        candidate_quantity=0, candidate_state="HOLD",
        candidate_reasons=["BLOCKED_ZERO_UNRESERVED"],
        candidate_evidence="INFERRED",
    )]
    payload["designs"] = [design_row(
        observed=10, requested_quantity=13, reserved_quantity=10,
        unmet_quantity=3,
    )]
    return payload


NOW = "2026-09-29T02:00:00Z"  # pinned clock: fixtures captured 2h earlier

# Pinned wall clock for the CLI path: the registry handler reads the
# real clock (caller-owned, correct per the pinned purity decision);
# tests pin it so freshness assertions never decay with the calendar.
_CLI_NOW = datetime.datetime(2026, 9, 29, 2, 0, 0,
                             tzinfo=datetime.timezone.utc)


class _TempSnapshotsMixin:
    """Registry over a MagicMock client pointing at a temp snapshot dir."""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="inv_transfers_cli_")
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.registry = self._make_registry({"snapshots_dir": self.tmp})
        patcher = patch("sdk.commands.datetime")
        mocked = patcher.start()
        mocked.datetime.now.return_value = _CLI_NOW
        mocked.datetime.timezone = datetime.timezone
        self.addCleanup(patcher.stop)

    def _make_registry(self, inventory_settings=None):
        from sdk.client import Client
        from sdk.commands import CommandRegistry

        client = MagicMock(spec=Client)
        if inventory_settings is not None:
            client.settings = {"inventory": inventory_settings}
        return CommandRegistry(client)

    def _write(self, name, payload):
        with open(os.path.join(self.tmp, name), "w", encoding="utf-8") as h:
            json.dump(payload, h)

    def _run(self, subcommand, registry=None):
        handler = (registry or self.registry).get("inventory")["handler"]
        return handler([subcommand])


