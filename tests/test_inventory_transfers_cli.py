class TestTransfersFailClosed(_TempSnapshotsMixin, unittest.TestCase):

    def _assert_refused(self, out):
        self.assertIn("inventory transfers: REFUSED fail-closed.", out)
        self.assertIn("The whole view refuses", out)

    def test_malformed_json_refuses_whole_view(self):
        self._write("a.json", source_payload())
        with open(os.path.join(self.tmp, "bad.json"), "w",
                  encoding="utf-8") as h:
            h.write('{"version": 1, "identity": {')
        self._assert_refused(self._run("transfers"))

    def test_duplicate_user_id_refuses_whole_view(self):
        self._write("a.json", source_payload())
        self._write("a2.json", source_payload())  # same user_id 101
        self._assert_refused(self._run("transfers"))

    def test_secret_bearing_snapshot_refuses_whole_view(self):
        payload = source_payload()
        payload["identity"]["accessToken"] = "Bearer not-a-real-token"
        self._write("secret.json", payload)
        self._assert_refused(self._run("transfers"))

    def test_unreadable_file_refuses_whole_view(self):
        self._write("a.json", source_payload())
        locked = os.path.join(self.tmp, "locked.json")
        with open(locked, "w", encoding="utf-8") as h:
            h.write(json.dumps(deficit_payload()))
        os.chmod(locked, 0o000)
        self.addCleanup(os.chmod, locked, 0o644)
        self._assert_refused(self._run("transfers"))

    def test_refusal_names_the_offending_file(self):
        with open(os.path.join(self.tmp, "bad.json"), "w",
                  encoding="utf-8") as h:
            h.write('{"version": 9}')
        out = self._run("transfers")
        self._assert_refused(out)
        self.assertIn("bad.json", out)


