class TestTransfersDispatch(_TempSnapshotsMixin, unittest.TestCase):

    def test_transfers_dispatches_to_pairing_view(self):
        self._write("a.json", source_payload())
        self._write("b.json", deficit_payload())
        out = self._run("transfers")
        self.assertIn("=== Inventory transfers (READ-ONLY Task I", out)
        self.assertIn("source 101 (fresh) -> destination 202 (fresh)", out)
        self.assertIn("design 501", out)
        self.assertIn("proposed 0", out)
        self.assertIn("HOLD_UNVERIFIED_TRANSFERABILITY", out)
        self.assertIn("actionable=false", out)

    def test_registry_pairing_output_matches_pure_renderer(self):
        """Thin-wrapper parity: the CLI handler output must be byte-
        identical to calling the pure renderer with the same loaded
        snapshots and the same pinned now (the wrapper adds nothing)."""
        from sdk.inventory import snapshot_from_json

        self._write("a.json", source_payload())
        self._write("b.json", deficit_payload())
        cli_out = self._run("transfers")
        texts = []
        for name in sorted(os.listdir(self.tmp)):
            if name.endswith(".json"):
                with open(os.path.join(self.tmp, name), encoding="utf-8") as h:
                    texts.append(h.read())
        snapshots = [snapshot_from_json(t) for t in texts]
        pure_out = render_transfers_view(snapshots, now=NOW)
        self.assertEqual(cli_out, pure_out)

    def test_accounts_and_deficits_unchanged_by_new_subcommand(self):
        self._write("a.json", source_payload())
        self._write("b.json", deficit_payload())
        accounts = self._run("accounts")
        deficits = self._run("deficits")
        self.assertIn("=== Inventory accounts (READ-ONLY Task H", accounts)
        self.assertIn("=== Inventory deficits (READ-ONLY Task H", deficits)
        # Task H wording survives the Task I wiring.
        self.assertIn("Candidate does not mean transferable.", accounts)
        self.assertIn("Candidate does not mean transferable.", deficits)

    def test_unknown_subcommand_lists_transfers_verb(self):
        out = self._run("frobnicate")
        self.assertIn("Unknown inventory subcommand: frobnicate", out)
        self.assertIn("inventory transfers", out)

    def test_transfers_help_reaches_inventory_verb(self):
        out = self.registry._cmd_help(["inventory"])
        self.assertIn("transfers", out)


